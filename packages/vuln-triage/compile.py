"""Compile the vulnerability triage graph into each scanner's own format.

Usage: compile.py <vulnerabilities.ttl> <shapes.ttl> <output-dir> <timestamp>

The triage lives in one RDF graph, written in Turtle (ADR 0024). This
script validates it against the SHACL shapes, then writes:

  vulnix.toml     the whitelist vulnix reads (`vulnix --whitelist`)
  openvex.json    an OpenVEX document of the permanent statements, for any
                  VEX-aware scanner such as grype (`grype --vex`)
  accepted.json   the accepted risks (status "affected"), so a scanner's
                  report can label those findings with their expiry

<timestamp> is the OpenVEX document's timestamp, in seconds since the
epoch; the flake passes the commit's time, so the build stays reproducible.

Validation failures are printed and exit non-zero, so `nix build
.#vuln-triage` fails on a statement that breaks the triage rules.
"""

import json
import re
import sys
from collections import OrderedDict
from datetime import datetime, timezone
from pathlib import Path

from pyshacl import validate
from rdflib import RDF, RDFS, Graph, Namespace

VEX = Namespace("https://openvex.dev/ns/v0.2.0#")
TRIAGE = Namespace("https://huwd.github.io/declarative_laptop/ns/triage#")
NVD = "https://nvd.nist.gov/vuln/detail/"
PURL = re.compile(r"^pkg:nix/(?P<name>[^@]+)(?:@(?P<version>.+))?$")
ISSUE = re.compile(r"^https://github\.com/huwd/declarative_laptop/(issues|pull)/\d+$")


def text(literal):
    """Join a multi-line literal into one paragraph.

    Statements keep one sentence per source line, as the style guide asks
    of prose, so whitespace inside a literal carries no meaning.
    """
    return " ".join(str(literal).split())


def sort_key(term):
    return str(term)


def load(data_path, shapes_path):
    data = Graph().parse(data_path, format="turtle")
    shapes = Graph().parse(shapes_path, format="turtle")
    conforms, _, report = validate(data, shacl_graph=shapes, advanced=True)
    if not conforms:
        sys.stderr.write(report)
        sys.exit(1)
    return data


def statements(graph):
    """Yield each statement as a plain dict, in a stable order."""
    for subject in sorted(graph.subjects(RDF.type, TRIAGE.Statement), key=sort_key):
        products = []
        for product in sorted(graph.objects(subject, VEX.product), key=sort_key):
            match = PURL.match(str(product))
            if not match:
                sys.exit(f"{subject}: product {product} is not a pkg:nix purl")
            products.append(match.groupdict())
        cves = []
        for cve in graph.objects(subject, VEX.vulnerability):
            if not str(cve).startswith(NVD):
                sys.exit(f"{subject}: vulnerability {cve} is not an NVD URL")
            cves.append(str(cve)[len(NVD):])
        until = graph.value(subject, TRIAGE.until)
        action = graph.value(subject, VEX.actionStatement)
        links = sorted(str(link) for link in graph.objects(subject, RDFS.seeAlso))
        yield {
            "id": str(subject),
            "products": products,
            "cves": sorted(cves),
            "status": str(graph.value(subject, VEX.status)),
            "justification": str(graph.value(subject, VEX.justification) or ""),
            "notes": text(graph.value(subject, VEX.statusNotes)),
            "action": text(action) if action is not None else None,
            "until": str(until) if until is not None else None,
            "issue": next((link for link in links if ISSUE.match(link)), None),
        }


def vulnix_key(product):
    """vulnix keys entries by derivation name: pname-version, or pname alone."""
    if product["version"] is None:
        return product["name"]
    return f'{product["name"]}-{product["version"]}'


def toml_string(value):
    # A JSON string is a valid TOML basic string for this content.
    return json.dumps(value, ensure_ascii=False)


def vulnix_toml(graph_statements):
    """Group statements by vulnix key.

    vulnix allows one `until` per key, so a key whose statements mix
    permanent and accepted-risk CVEs takes the earliest `until`: the
    permanent ones reappear with the others, which is the safe direction.
    """
    entries = OrderedDict()
    for statement in graph_statements:
        for product in statement["products"]:
            entry = entries.setdefault(
                vulnix_key(product), {"cve": [], "until": None, "issue": None, "comment": []}
            )
            entry["cve"].extend(c for c in statement["cves"] if c not in entry["cve"])
            if statement["until"] and (entry["until"] is None or statement["until"] < entry["until"]):
                entry["until"] = statement["until"]
            entry["issue"] = entry["issue"] or statement["issue"]
            entry["comment"].append(statement["notes"])
            if statement["action"]:
                entry["comment"].append("Mitigation: " + statement["action"])

    lines = [
        "# Generated by `nix build .#vuln-triage` from triage/vulnerabilities.ttl.",
        "# Do not edit: change the Turtle source instead (ADR 0024).",
    ]
    for key in sorted(entries):
        entry = entries[key]
        lines.append("")
        lines.append(f"[{toml_string(key)}]")
        lines.append("cve = [ " + ", ".join(toml_string(c) for c in sorted(entry["cve"])) + " ]")
        if entry["until"]:
            lines.append(f'until = {toml_string(entry["until"])}')
        if entry["issue"]:
            lines.append(f'issue_url = {toml_string(entry["issue"])}')
        if len(entry["comment"]) == 1:
            lines.append(f'comment = {toml_string(entry["comment"][0])}')
        else:
            lines.append("comment = [")
            lines.extend(f"  {toml_string(c)}," for c in entry["comment"])
            lines.append("]")
    return "\n".join(lines) + "\n"


def purl(product):
    if product["version"] is None:
        return f'pkg:nix/{product["name"]}'
    return f'pkg:nix/{product["name"]}@{product["version"]}'


def openvex(graph_statements, timestamp):
    """The permanent statements, one OpenVEX statement for each CVE.

    Only not_affected and fixed statements go in: the shapes make those
    permanent, so this document needs no expiry. Accepted risks stay out,
    so a VEX-aware scanner keeps reporting them; accepted.json labels them.
    A purl without a version matches every version of the package in grype.
    """
    vex_statements = []
    for statement in graph_statements:
        if statement["status"] not in ("not_affected", "fixed"):
            continue
        for cve in statement["cves"]:
            entry = {
                "@id": f'{statement["id"]}/{cve}',
                "vulnerability": {"@id": NVD + cve, "name": cve},
                "products": [{"@id": purl(p)} for p in statement["products"]],
                "status": statement["status"],
            }
            if statement["status"] == "not_affected":
                entry["justification"] = statement["justification"]
            entry["status_notes"] = statement["notes"]
            vex_statements.append(entry)
    document = {
        "@context": "https://openvex.dev/ns/v0.2.0",
        "@id": "https://github.com/huwd/declarative_laptop/blob/main/triage/vulnerabilities.ttl",
        "author": "https://huwdiprose.co.uk/profile#me",
        "tooling": "packages/vuln-triage/compile.py",
        "timestamp": timestamp,
        "version": 1,
        "statements": vex_statements,
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def accepted(graph_statements):
    risks = [
        {
            "id": s["id"],
            "products": [purl(p) for p in s["products"]],
            "cves": s["cves"],
            "until": s["until"],
            "mitigation": s["action"],
            "notes": s["notes"],
        }
        for s in graph_statements
        if s["status"] == "affected"
    ]
    return json.dumps(risks, indent=2, ensure_ascii=False) + "\n"


def main():
    data_path, shapes_path, out, epoch = sys.argv[1:5]
    graph = load(data_path, shapes_path)
    out_dir = Path(out)
    out_dir.mkdir(parents=True, exist_ok=True)
    found = list(statements(graph))
    timestamp = datetime.fromtimestamp(int(epoch), timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    (out_dir / "vulnix.toml").write_text(vulnix_toml(found))
    (out_dir / "openvex.json").write_text(openvex(found, timestamp))
    (out_dir / "accepted.json").write_text(accepted(found))


if __name__ == "__main__":
    main()
